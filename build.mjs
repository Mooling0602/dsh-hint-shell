/**
 * Bundles a plugin's Client half into the single-file form the Harness module
 * loader expects.
 *
 * `window.__ModuleLoader__.load({ id, factory(require) })` hands the plugin a
 * `require` that resolves *host* packages only; it cannot resolve relative
 * module specifiers. The Client bundle must therefore be one self-contained
 * file, which is what this script produces from `src/` into `dist/`.
 *
 * `dist/` is git-ignored build output: the repository ships sources only, and
 * the built files travel inside the release tarball (see PUBLISHING.md).
 *
 * Package name, module id, and bundle global are read from package.json so the
 * script stays identical across plugins.
 *
 * Usage: node build.mjs
 */

import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const manifestPath = resolve(here, 'package.json');
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));

const name = manifest.name;
if (typeof name !== 'string' || name.length === 0) {
  throw new Error('package.json must declare a `name`');
}

const entry = resolve(here, 'src/index.ts');
const outDir = resolve(here, 'dist');
const outfile = resolve(outDir, 'client.js');

// The Host half is plain ESM evaluated by the Host process, not by the browser
// loader. It is built separately (rather than importing .ts directly) so the
// shipped file never depends on the runtime having TypeScript stripping enabled.
const hostEntry = resolve(here, 'host.ts');
const hostOutfile = resolve(outDir, 'index.js');

// The IIFE global is derived from the package name so no two plugins collide if
// the host ever evaluates two bundles in one realm.
const globalName = '__dsh_' + name.replace(/^@/, '').replace(/[^a-zA-Z0-9]/g, '_');

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: 'iife',
  globalName,
  platform: 'browser',
  target: 'es2022',
  legalComments: 'none',
  logLevel: 'warning',
  // Keep CJK literals readable in the shipped bundle instead of \uXXXX escapes.
  charset: 'utf8',
  // The page is JSX; the automatic runtime is what React 19 expects, and it
  // keeps each component file free of a manual `React` import.
  jsx: 'automatic',
  // Host packages come from the loader's `require`; never bundle them. The
  // `dsh.client.external` list in package.json must name the same packages, or
  // the loader would never put them in the module table for this bundle.
  external: [
    'react',
    'react-dom',
    'react/jsx-runtime',
    '@deepseek-ai/cordis',
    '@deepseek-ai/dsh-client-store',
    '@deepseek-ai/dsh-client-ui-primitives',
    '@deepseek-ai/dsh-client-ui-slots',
  ],
});

const bundled = result.outputFiles?.[0];
if (bundled === undefined) throw new Error('esbuild produced no output');

const indented = bundled.text
  .trim()
  .split('\n')
  .map((line) => (line.length === 0 ? '' : `    ${line}`))
  .join('\n');

const wrapped = `/**
 * ${name} — Client half, generated by build.mjs.
 * Source of truth: src/*.ts. Do not edit this file by hand.
 */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(name)},
  factory(require) {
    'use strict';
    const module = { exports: {} };
    const exports = module.exports;
${indented}
    return ${globalName};
  },
});
`;

await mkdir(outDir, { recursive: true });
await writeFile(outfile, wrapped, 'utf8');

// Fail loudly if the wrapper ever regresses.
if (!wrapped.includes('__ModuleLoader__')) throw new Error('output missing loader registration');
if (!wrapped.includes(`id: ${JSON.stringify(name)}`)) throw new Error('output missing module id');
if (!wrapped.includes(globalName)) throw new Error('output missing bundle global');

console.log(`built ${name} -> dist/client.js (${Buffer.byteLength(wrapped, 'utf8')} bytes)`);

// ── Host half ──────────────────────────────────────────────────────────────
// Plain ESM for the Host process. Node-provided builtins stay external; the
// bundle is self-contained otherwise.
const hostResult = await build({
  entryPoints: [hostEntry],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  legalComments: 'none',
  logLevel: 'warning',
  charset: 'utf8',
  // The settings system recognises a schema by identity: `SettingsForms.schema`
  // requires the very class the Host uses, and an inlined copy would be a
  // different class with the same shape. `schemastery` is therefore resolved
  // from the Host's own module tree, exactly as `@deepseek-ai/cordis` is; both
  // are declared as peer dependencies for that reason.
  external: ['@deepseek-ai/schemastery', '@deepseek-ai/cordis'],
});

const hostBundle = hostResult.outputFiles?.[0];
if (hostBundle === undefined) throw new Error('esbuild produced no host output');

const hostBanner = `/**
 * ${name} — Host half, generated by build.mjs.
 * Source of truth: host.ts + src/*.ts. Do not edit this file by hand.
 */
`;

await writeFile(hostOutfile, hostBanner + hostBundle.text, 'utf8');
console.log(`built ${name} -> dist/index.js (${Buffer.byteLength(hostBanner + hostBundle.text, 'utf8')} bytes)`);
